// Regenerates src/icons/paths.ts from lucide-static (ISC).
//
// The library has no runtime dependencies, so the icons it needs are copied in
// at author time rather than imported: this script reads the curated list
// below out of node_modules/lucide-static and writes each icon's inner SVG
// markup as a string. Run `npm run icons` after adding a name to the list.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const NAMES = [
  'activity', 'arrow-right', 'arrow-up-right', 'book-open', 'check', 'chevron-down', 'chevron-left',
  'chevron-right', 'chevron-up', 'circle-alert', 'circle-check', 'circle-help', 'circle-x', 'copy',
  'cpu', 'database', 'download', 'external-link', 'file-text', 'gauge', 'git-branch', 'github',
  'info', 'layers', 'list-filter', 'menu', 'moon', 'network', 'pause', 'play', 'plus', 'refresh-cw',
  'rotate-ccw', 'search', 'server', 'settings', 'share-2', 'skip-back', 'skip-forward',
  'sliders-horizontal', 'sun', 'terminal', 'triangle-alert', 'upload', 'waypoints', 'x', 'zap',
];

const entries = [];
for (const name of NAMES) {
  let svg;
  try {
    svg = readFileSync(resolve(root, 'node_modules/lucide-static/icons', `${name}.svg`), 'utf8');
  } catch {
    console.error(`skip: ${name} is not in this lucide-static version`);
    continue;
  }
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<svg[\s\S]*?>/, '')
    .replace('</svg>', '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  entries.push(`  '${name}': '${inner.replace(/'/g, "\\'")}',`);
}

const out = `/* Generated by scripts/build-icons.mjs from lucide-static — do not edit by hand.
 * Icons © Lucide Contributors, ISC licence (src/icons/LICENSE-Lucide.txt). */
export const ICON_PATHS = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`;
mkdirSync(resolve(root, 'src/icons'), { recursive: true });
writeFileSync(resolve(root, 'src/icons/paths.ts'), out);
writeFileSync(
  resolve(root, 'src/icons/LICENSE-Lucide.txt'),
  readFileSync(resolve(root, 'node_modules/lucide-static/LICENSE'), 'utf8'),
);
console.log(`wrote ${entries.length} icons`);
